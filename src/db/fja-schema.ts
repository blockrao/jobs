import {
  pgTable, text, integer, bigint, numeric, date, timestamp, jsonb,
  uniqueIndex, index,
} from "drizzle-orm/pg-core";

/**
 * Private FreeJobAlert research inventory.
 * These tables hold source evidence/candidates only; they are not canonical
 * page records and must never be used as a public-page query source.
 */
export const fjaJobInventory = pgTable("fja_job_inventory", {
  id: bigint("id", { mode: "bigint" }).primaryKey().generatedAlwaysAsIdentity(),
  sourceSlug: text("source_slug").notNull().default("freejobalert"),
  externalId: text("external_id").notNull(),
  sourceUrl: text("source_url").notNull(),
  title: text("title").notNull(),
  organizationName: text("organization_name"),
  listingCategory: text("listing_category"),
  publishedDate: date("published_date"),
  applicationStartDate: date("application_start_date"),
  applicationEndDate: date("application_end_date"),
  advertisementNumber: text("advertisement_number"),
  qualification: text("qualification"),
  vacancyCount: integer("vacancy_count"),
  detailStatus: text("detail_status").notNull().default("PENDING"),
  sourceStatus: text("source_status").notNull().default("UNKNOWN"),
  details: jsonb("details").notNull().default({}),
  otherInfoRaw: jsonb("other_info_raw").notNull().default({}),
  rawText: text("raw_text"),
  contentHash: text("content_hash").notNull(),
  officialNotificationUrl: text("official_notification_url"),
  firstSeenAt: timestamp("first_seen_at", { withTimezone: true }).notNull().defaultNow(),
  lastSeenAt: timestamp("last_seen_at", { withTimezone: true }).notNull().defaultNow(),
  lastCrawlRunId: text("last_crawl_run_id"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => [
  uniqueIndex("fja_job_inventory_source_external_unique").on(table.sourceSlug, table.externalId),
  index("fja_job_inventory_published_date_idx").on(table.publishedDate),
  index("fja_job_inventory_application_end_idx").on(table.applicationEndDate),
  index("fja_job_inventory_category_idx").on(table.listingCategory),
  index("idx_fja_job_inventory_official_notification_url").on(table.officialNotificationUrl),
]).enableRLS();

export const fjaPostInventory = pgTable("fja_post_inventory", {
  id: bigint("id", { mode: "bigint" }).primaryKey().generatedAlwaysAsIdentity(),
  recruitmentInventoryId: bigint("recruitment_inventory_id", { mode: "bigint" }).notNull().references(() => fjaJobInventory.id, { onDelete: "cascade" }),
  sourceSlug: text("source_slug").notNull().default("freejobalert"),
  externalId: text("external_id").notNull(),
  sourcePostKey: text("source_post_key").notNull(),
  postNameRaw: text("post_name_raw"),
  postNameNormalizedCandidate: text("post_name_normalized_candidate"),
  sourcePostCodeRaw: text("source_post_code_raw"),
  vacancyCountRaw: text("vacancy_count_raw"),
  vacancyCountCandidate: integer("vacancy_count_candidate"),
  qualificationRaw: text("qualification_raw"),
  experienceRaw: text("experience_raw"),
  ageLimitRaw: text("age_limit_raw"),
  ageReferenceDateRaw: text("age_reference_date_raw"),
  ageRelaxationRulesRaw: text("age_relaxation_rules_raw"),
  salaryRaw: text("salary_raw"),
  salaryMinCandidate: numeric("salary_min_candidate", { precision: 14, scale: 2 }),
  salaryMaxCandidate: numeric("salary_max_candidate", { precision: 14, scale: 2 }),
  salaryCurrencyCandidate: text("salary_currency_candidate"),
  salaryPeriodCandidate: text("salary_period_candidate"),
  salaryTypeCandidate: text("salary_type_candidate"),
  salaryNormalizationStatus: text("salary_normalization_status").notNull().default("NEEDS_REVIEW"),
  minAgeYearsCandidate: integer("min_age_years_candidate"),
  maxAgeYearsCandidate: integer("max_age_years_candidate"),
  ageReferenceDateCandidate: date("age_reference_date_candidate"),
  ageNormalizationStatus: text("age_normalization_status").notNull().default("NEEDS_REVIEW"),
  officialSourcePage: integer("official_source_page"),
  verifiedOfficialSourceUrl: text("verified_official_source_url"),
  verificationNotes: text("verification_notes"),
  verifiedAt: timestamp("verified_at", { withTimezone: true }),
  payLevelRaw: text("pay_level_raw"),
  employmentTypeRaw: text("employment_type_raw"),
  tenureRaw: text("tenure_raw"),
  locationRaw: text("location_raw"),
  dutiesResponsibilitiesRaw: text("duties_responsibilities_raw"),
  eligibilityConditionsRaw: text("eligibility_conditions_raw"),
  milestonesRaw: jsonb("milestones_raw").notNull().default([]),
  applicationSelectionRaw: jsonb("application_selection_raw").notNull().default([]),
  otherInfoRaw: jsonb("other_info_raw").notNull().default({}),
  sourceTableRowRaw: jsonb("source_table_row_raw"),
  extractionStatus: text("extraction_status").notNull().default("PENDING"),
  officialVerificationStatus: text("official_verification_status").notNull().default("PENDING"),
  contentHash: text("content_hash").notNull(),
  lastCrawlRunId: text("last_crawl_run_id"),
  firstSeenAt: timestamp("first_seen_at", { withTimezone: true }).notNull().defaultNow(),
  lastSeenAt: timestamp("last_seen_at", { withTimezone: true }).notNull().defaultNow(),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => [
  uniqueIndex("fja_post_inventory_identity_unique").on(table.sourceSlug, table.externalId, table.sourcePostKey),
  index("fja_post_inventory_parent_idx").on(table.recruitmentInventoryId),
  index("fja_post_inventory_name_idx").on(table.postNameRaw),
  index("fja_post_inventory_salary_status_idx").on(table.salaryNormalizationStatus),
  index("fja_post_inventory_age_status_idx").on(table.ageNormalizationStatus),
]).enableRLS();

export const fjaSourceCaptures = pgTable("fja_source_captures", {
  id: bigint("id", { mode: "bigint" }).primaryKey().generatedAlwaysAsIdentity(),
  recruitmentInventoryId: bigint("recruitment_inventory_id", { mode: "bigint" }).notNull().references(() => fjaJobInventory.id, { onDelete: "restrict" }),
  sourceSlug: text("source_slug").notNull().default("freejobalert"),
  externalId: text("external_id").notNull(),
  sourceUrl: text("source_url").notNull(),
  htmlSha256: text("html_sha256").notNull(),
  normalizedTextSha256: text("normalized_text_sha256"),
  rawHtml: text("raw_html").notNull(),
  runId: text("run_id"),
  capturedAt: timestamp("captured_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => [
  uniqueIndex("fja_source_captures_identity_hash_unique").on(table.sourceSlug, table.externalId, table.htmlSha256),
  index("fja_source_captures_parent_idx").on(table.recruitmentInventoryId, table.capturedAt),
]).enableRLS();
